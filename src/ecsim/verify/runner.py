"""One verification run: tests + coverage + guidelines + traceability, and an HTML report."""
from __future__ import annotations

import html
from dataclasses import dataclass, field
from datetime import datetime

from ecsim.model.backends import EcsimBackend
from ecsim.model.coverage import CoverageReport
from ecsim.model.guidelines import Finding, check_model
from ecsim.model.mil import MilReport, run_tests
from ecsim.verify.requirements import Requirement, TraceRow, trace_matrix


@dataclass
class VerificationRun:
    model_name: str
    test_source: str
    mil: MilReport
    coverage: CoverageReport | None
    findings: list[Finding]
    trace: list[TraceRow] = field(default_factory=list)


def verify(model_json: str, spec: dict, requirements: list[Requirement], test_source: str) -> VerificationRun:
    import json
    from ecsim.learning.graders.test_design import coverage_of
    mil = run_tests(EcsimBackend(), model_json, spec)
    cov = None
    if not mil.errors:
        ol = [t for t in spec["tests"] if t.get("type", "open_loop") == "open_loop"]
        cov = coverage_of(model_json, ol) if ol else None
    name = json.loads(model_json).get("name", "model")
    return VerificationRun(name, test_source, mil, cov, check_model(model_json), trace_matrix(requirements, mil.outcomes))


def html_report(run: VerificationRun, learner: str) -> str:
    e = html.escape
    ok = run.mil.passed
    rows = "".join(f"<tr class={'ok' if o.passed else 'bad'}><td>{e(o.test)}</td><td>{e(o.name)}</td>"
                   f"<td>{'PASS' if o.passed else 'FAIL'}</td><td>{e(o.detail)}</td></tr>" for o in run.mil.outcomes)
    errs = "".join(f"<li>{e(x)}</li>" for x in run.mil.errors)
    cov = ""
    if run.coverage:
        miss = "".join(f"<li>{e(b)}: {e(o)}</li>" for b, o in run.coverage.missing())
        cov = (f"<h2>Model coverage (decision)</h2><p><b>{run.coverage.covered}/{run.coverage.total}</b> outcomes "
               f"({run.coverage.ratio:.0%}) from open-loop tests.</p>" + (f"<ul>{miss}</ul>" if miss else "<p>Nothing uncovered.</p>"))
    finds = "".join(f"<tr><td>{e(f.severity)}</td><td>{e(f.rule)}</td><td>{e(f.where)}</td><td>{e(f.message)}</td></tr>"
                    for f in run.findings) or "<tr><td colspan=4>No findings.</td></tr>"
    trace = "".join(f"<tr class={'ok' if r.status == 'passed' else 'bad'}><td>{e(r.req_id)}</td><td>{e(r.title)}</td>"
                    f"<td>{e(r.status)}</td><td>{len(r.checks)}</td></tr>" for r in run.trace) or \
        "<tr><td colspan=4>No requirements in the Requirements Manager yet.</td></tr>"
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>Verification report: {e(run.model_name)}</title>
<style>body{{font-family:system-ui,sans-serif;max-width:1000px;margin:2em auto;color:#1d2430}}table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #d0d5dd;padding:4px 8px;text-align:left;font-size:13px}}th{{background:#eef1f5}}.ok td:nth-child(3){{color:#1b7a3a}}
.bad td:nth-child(3){{color:#b3261e;font-weight:600}}.verdict{{font-size:20px;font-weight:700;color:{'#1b7a3a' if ok else '#b3261e'}}}
.note{{color:#5b6573;font-size:12px}}</style></head><body>
<h1>Verification report: {e(run.model_name)}</h1>
<p>Prepared by {e(learner)} · {datetime.now().strftime('%Y-%m-%d %H:%M')} · tests: {e(run.test_source)} · backend: {e(run.mil.backend)}</p>
<p class="verdict">{'All checks passed' if ok else 'Checks failed'} ({sum(o.passed for o in run.mil.outcomes)}/{len(run.mil.outcomes)})</p>
{f'<ul>{errs}</ul>' if errs else ''}
<h2>Requirement checks (MIL)</h2><table><tr><th>Test</th><th>Check</th><th>Result</th><th>Evidence</th></tr>{rows}</table>
{cov}
<h2>Traceability</h2><table><tr><th>Requirement</th><th>Title</th><th>Status</th><th>Checks</th></tr>{trace}</table>
<h2>Modelling-guideline findings</h2><table><tr><th>Severity</th><th>Rule</th><th>Where</th><th>Finding</th></tr>{finds}</table>
<p class="note">Generated by ECSim, a training simulator. This report is training evidence and not a qualified tool output.</p>
</body></html>"""
