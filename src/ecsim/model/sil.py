"""Software-in-the-loop: compile generated C, step it through the MIL harness, compare back-to-back.

The generated model code is compiled with the same strict flags used for learner C
(-std=c99 -Wall -Wextra -Werror -pedantic), so "the code generator produced warning-free C"
is itself checked. The library is loaded in-process; it is generated by ECSim (no pointers or
dynamic memory from user input), so it cannot fault the host.
"""
from __future__ import annotations

import ctypes
import itertools
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from ecsim.ecu.build import CFLAGS, IS_WINDOWS, LIB_SUFFIX
from ecsim.ecu.vecu import _unload
from ecsim.model.backends.ecsim_backend import EcsimBackend
from ecsim.model.blocks import ModelError
from ecsim.model.codegen import GeneratedCode, generate_c
from ecsim.model.core import Compiled
from ecsim.model.mil import MilReport, TestTrace, run_tests

_IDS = itertools.count(1)


def _wrapper(g: GeneratedCode) -> str:
    m = g.name
    lines = [f'#include "{m}.h"', "void sil_init(void) { " + f"{m}_initialize();" + " }",
             "void sil_step(const double *u, double *y)", "{"]
    for i, n in enumerate(g.inports):
        lines.append(f"    {m}_U.{n} = (real_T)u[{i}];")
    if not g.inports:
        lines.append("    (void)u;")
    lines.append(f"    {m}_step();")
    for i, n in enumerate(g.outports):
        lines.append(f"    y[{i}] = (double){m}_Y.{n};")
    if not g.outports:
        lines.append("    (void)y;")
    lines.append("}")
    return "\n".join(lines) + "\n"


@dataclass
class SilBuild:
    ok: bool
    log: str
    lib: Path | None = None
    code: GeneratedCode | None = None
    workdir: Path | None = None


def build_sil(code: GeneratedCode, workdir: Path, compiler: str = "gcc") -> SilBuild:
    if shutil.which(compiler) is None:
        return SilBuild(False, f"C compiler '{compiler}' not found.")
    workdir.mkdir(parents=True, exist_ok=True)
    for name, text in code.files.items():
        (workdir / name).write_text(text, encoding="utf-8")
    (workdir / "sil_wrapper.c").write_text(_wrapper(code), encoding="utf-8")
    lib = workdir / f"sil_{os.getpid()}_{next(_IDS)}{LIB_SUFFIX}"
    pic = [] if IS_WINDOWS else ["-fPIC"]
    cmd = [compiler, *CFLAGS, *pic, "-shared", f"{code.name}.c", "sil_wrapper.c", "-lm", "-o", str(lib)]
    r = subprocess.run(cmd, cwd=workdir, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120)
    if r.returncode != 0:
        return SilBuild(False, "Generated code failed to compile (this is a code generator defect, please report it):\n"
                        + r.stderr[:4000], code=code, workdir=workdir)
    return SilBuild(True, r.stderr, lib, code, workdir)


class SilModel:
    def __init__(self, build: SilBuild) -> None:
        self.lib = ctypes.CDLL(str(build.lib))
        self.n_in, self.n_out = len(build.code.inports), len(build.code.outports)
        self._u = (ctypes.c_double * max(1, self.n_in))()
        self._y = (ctypes.c_double * max(1, self.n_out))()
        self.lib.sil_init.restype = None
        self.lib.sil_step.restype = None
        self.lib.sil_init()

    def step(self, u: list[float]) -> list[float]:
        for i, v in enumerate(u):
            self._u[i] = float(v)
        self.lib.sil_step(self._u, self._y)
        return [self._y[i] for i in range(self.n_out)]

    def close(self) -> None:
        if self.lib is not None:
            _unload(self.lib)
            self.lib = None


class SilBackend(EcsimBackend):
    """Same harness as the ECSim backend, but each step runs the generated, compiled C."""

    def __init__(self, dtype: str = "double", compiler: str = "gcc") -> None:
        self.dtype, self.compiler = dtype, compiler
        self.name = f"SIL ({dtype}-precision generated C)"
        self._tmp = None
        self._models: list[SilModel] = []
        self.build: SilBuild | None = None

    def prepare(self, submission: str, spec: dict) -> Compiled:
        c = super().prepare(submission, spec)
        self._tmp = tempfile.TemporaryDirectory(prefix="ecsim_sil_", ignore_cleanup_errors=True)
        self.build = build_sil(generate_c(c, self.dtype), Path(self._tmp.name), self.compiler)
        if not self.build.ok:
            raise ModelError(self.build.log)
        return c

    def stepper(self, c: Compiled):
        m = SilModel(self.build)          # fresh instance = fresh static data (new library copy)
        self._models.append(m)
        return m

    def release(self, c: Compiled) -> None:
        for m in self._models:
            m.close()
        self._models.clear()
        if self._tmp is not None:
            self._tmp.cleanup()
            self._tmp = None

    def stepper_lib_fresh(self) -> None:  # pragma: no cover - documentation hook
        pass


@dataclass
class B2BResult:
    test: str
    signal: str
    max_abs: float
    at_t: float
    passed: bool


@dataclass
class B2BReport:
    mil: MilReport
    sil: MilReport
    comparisons: list[B2BResult] = field(default_factory=list)

    @property
    def equivalent(self) -> bool:
        return bool(self.comparisons) and all(c.passed for c in self.comparisons)


def back_to_back(submission: str, spec: dict, dtype: str = "double", abs_tol: float = 1e-9,
                 rel_tol: float = 0.0) -> B2BReport:
    """Run the same tests on MIL (double, model) and SIL (generated C) and compare every signal."""
    mil = run_tests(EcsimBackend(), submission, spec)
    sil = run_tests(SilBackend(dtype), submission, spec)
    rep = B2BReport(mil, sil)
    for name, a in mil.traces.items():
        b = sil.traces.get(name)
        if b is None:
            continue
        for sig, ya in a.signals.items():
            yb = b.signals.get(sig)
            if yb is None:
                continue
            worst, at = 0.0, 0.0
            ok = True
            for t, va, vb in zip(a.t, ya, yb):
                d = abs(va - vb)
                if d > worst or (d != d):
                    worst, at = d, t
                if d != d or d > abs_tol + rel_tol * abs(va):
                    ok = False
            rep.comparisons.append(B2BResult(name, sig, worst, at, ok))
    return rep
